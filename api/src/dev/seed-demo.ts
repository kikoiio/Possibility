export interface SeedDemoResult {
  created: boolean
  worldId: string
  persons: number
  note?: string
}

/** 创建演示世界（按世界名 + isDemo 幂等）；owner 为 admin，须先跑 npm run seed */
export async function seedDemoWorld(db: Db, adminUsername = 'admin'): Promise<SeedDemoResult> {
  const admin = await db.select().from(users).where(eq(users.username, adminUsername)).get()
  if (!admin) throw new Error(`${adminUsername} 账号不存在，请先执行 npm run seed`)

  const existing = await db
    .select()
    .from(worlds)
    .where(and(eq(worlds.name, WORLD_NAME), eq(worlds.isDemo, true)))
    .get()
  if (existing) return { created: false, worldId: existing.id, persons: DEMO_PERSONS.length, note: '已存在，未重复创建' }

  const now = new Date().toISOString()
  const today = now.slice(0, 10)
  const worldId = crypto.randomUUID()
  const mainTimelineId = crypto.randomUUID()

  await db.insert(worlds).values({
    id: worldId,
    userId: admin.id,
    name: WORLD_NAME,
    description: WORLD_DESCRIPTION,
    locationsJson: JSON.stringify(LOCATIONS),
    status: 'running',
    isDemo: true,
    callsToday: 0,
    callsDay: today,
    createdAt: now,
  })

  await db.insert(timelines).values({
    id: mainTimelineId,
    worldId,
    parentTimelineId: null,
    forkScenarioJson: null,
    simNow: now,
    createdAt: now,
    status: 'active',
    ancestorIdsJson: '[]',
  })

  for (const p of DEMO_PERSONS) {
    const personId = crypto.randomUUID()
    await db.insert(persons).values({
      id: personId,
      userId: admin.id,
      name: p.name,
      modelJson: JSON.stringify(p.model),
      createdAt: now,
    })
    await db.insert(worldPersons).values({ worldId, personId, joinedAt: now })
    await db.insert(personStates).values({
      personId,
      timelineId: mainTimelineId,
      simTime: now,
      location: p.initial.location,
      activity: p.initial.activity,
      mood: p.initial.mood,
      goal: p.initial.goal,
      updatedRealAt: now,
      lastBeatSimTime: now,
    })
  }

  return { created: true, worldId, persons: DEMO_PERSONS.length }
}
